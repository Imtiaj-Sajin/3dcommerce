/** Flat list of every product with its space and category attached. */
export function flatten() {
  const out = [];
  for (const [spaceSlug, space] of Object.entries(APPAREL)) {
    for (const cat of space.categories) {
      cat.products.forEach((p, i) => {
        out.push({
          ...p,
          spaceSlug,
          categorySlug: cat.slug,
          slotIndex: i,
          imageFile: `apparel/${spaceSlug}-${cat.slug}-${i}.jpg`,
        });
      });
    }
  }
  return out;
}
